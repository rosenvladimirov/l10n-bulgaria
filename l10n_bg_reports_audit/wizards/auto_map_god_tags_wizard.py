class L10nBgAutoMapGodTagsWizard(models.TransientModel):
    _name = "l10n.bg.auto.map.god.tags.wizard"
    _description = "Auto-map NSI annual report tags to accounts (standard BG chart)"

    company_ids = fields.Many2many(
        comodel_name="res.company",
        required=True,
        default=lambda self: self.env.company,
    )
    overwrite = fields.Boolean(
        string="Overwrite existing",
        default=False,
        help="If unchecked (default), tags are ADDED to accounts already carrying "
             "the tag list. If checked, replaces tag_ids on matched accounts.",
    )
    applicability_filter = fields.Selection(
        [
            ("all", "All annual report tags"),
            ("gfo_balance", "Balance Sheet only"),
            ("gfo_pl", "Profit & Loss only"),
            ("gfo_cf", "Cash Flow only"),
            ("gfo_equity", "Changes in Equity only"),
            ("god", "NSI Activity Report only"),
        ],
        string="Apply to",
        default="all",
        required=True,
    )
    preview_text = fields.Text(readonly=True)
    matched_account_count = fields.Integer(readonly=True)
    matched_tag_count = fields.Integer(readonly=True)

    def _tag_dict_key(self, tag):
        """Build the NSI_TO_ACCOUNT_PREFIXES lookup key for a tag.

        For gfo_cf, append _in / _out based on position to match the dict.
        Other applicabilities use the bare NSI code.
        """
        nsi_code = tag.name.split(" — ")[0].strip()
        if tag.l10n_bg_applicability == "gfo_cf":
            suffix = "_in" if tag.l10n_bg_position == "inflow" else "_out"
            return nsi_code + suffix
        return nsi_code

    def _eligible_tags(self):
        domain = [("l10n_bg_applicability", "in",
                   ("gfo_balance", "gfo_pl", "gfo_cf", "gfo_equity", "god"))]
        if self.applicability_filter != "all":
            domain = [("l10n_bg_applicability", "=", self.applicability_filter)]
        return self.env["account.account.tag"].search(domain)

    def action_preview(self):
        self.ensure_one()
        lines = []
        total_matches = 0
        total_tags = 0
        for tag in self._eligible_tags():
            key = self._tag_dict_key(tag)
            prefixes = NSI_TO_ACCOUNT_PREFIXES.get(key)
            if not prefixes:
                continue
            accounts = self._search_accounts(prefixes)
            if not accounts:
                continue
            total_tags += 1
            total_matches += len(accounts)
            lines.append(
                f"{key} ({tag.l10n_bg_applicability}) → "
                f"{len(accounts)} accounts: "
                + ", ".join(a.code_store for a in accounts[:5])
                + ("…" if len(accounts) > 5 else "")
            )
        self.preview_text = "\n".join(lines) or _("No matches.")
        self.matched_tag_count = total_tags
        self.matched_account_count = total_matches
        return {
            "type": "ir.actions.act_window",
            "res_model": self._name,
            "res_id": self.id,
            "view_mode": "form",
            "target": "new",
        }

    def action_apply(self):
        self.ensure_one()
        total_writes = 0
        for tag in self._eligible_tags():
            key = self._tag_dict_key(tag)
            prefixes = NSI_TO_ACCOUNT_PREFIXES.get(key)
            if not prefixes:
                continue
            accounts = self._search_accounts(prefixes)
            if not accounts:
                continue
            for account in accounts:
                if self.overwrite:
                    account.tag_ids = [(6, 0, [tag.id])]
                else:
                    if tag not in account.tag_ids:
                        account.tag_ids = [(4, tag.id)]
                total_writes += 1
            _logger.info(
                "GOD auto-map: tag %s (%s) → %s accounts",
                key, tag.l10n_bg_applicability, len(accounts),
            )
        return {
            "type": "ir.actions.client",
            "tag": "display_notification",
            "params": {
                "title": _("GOD tag mapping applied"),
                "message": _("Wrote tag→account links on %s account(s).") % total_writes,
                "type": "success",
                "sticky": False,
            },
        }

    def _search_accounts(self, prefixes):
        prefix_leaves = [("code_store", "=like", f"{p}%") for p in prefixes]
        # OR all prefix leaves: (n-1) leading "|" operators, then leaves
        or_block = ["|"] * (len(prefixes) - 1) + prefix_leaves
        domain = [
            ("company_ids", "in", self.company_ids.ids),
            ("deprecated", "=", False),
        ] + or_block
        return self.env["account.account"].search(domain)
